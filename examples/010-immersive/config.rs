/// Vertical climb speed in meters/second when holding full forward/back.
/// Deliberately slow — a ladder is not a lift.
pub const LADDER_CLIMB_SPEED: f32 = 2.2;

/// How hard the body is pulled onto the ladder's centre line (exponential
/// `smooth_nudge` decay rate). The body overlaps the ladder's sensor volume
/// HL-style, so there's no standoff — just this pull toward the middle.
/// High enough to feel stuck, not so high it snaps visibly on grab.
pub const LADDER_SNAP_RATE: f32 = 16.0;

/// How far (meters) in front of the ladder's centre line the climber's body —
/// and so the camera — sits while locked on. The body hangs on the ladder's
